#!/usr/bin/env python3
"""Writes src/gdimetrics.inc: GDI's metrics for each FONT.DEF WINFONT, as the
HUD emulator's gdi.py answers them -- the cell CreateFontA(+height) maps to
(the em size whose VDMX cell fits the height, its ascent and descent) and the
advance width of every Windows-1252 character (the face's hdmx width at that
size where it has one, else its linear width rounded half to even).

The port's GDI stand-ins (TFontTable::Atlas) draw with these, so the port and
the emulator lay text out alike by construction; both stand for Win98 GDI
until a capture of it settles the rest (docs/ui/HUD_REBUILD.md, P6).

    gdi_metrics.py [OUT]        default: <repo>/src/gdimetrics.inc
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gdi  # noqa: E402
import ttf  # noqa: E402

# FONT.DEF's WINFONTs: (face, CreateFontA height, bold) -- Small / Numbers /
# Version, Med, SpellTitle, Dialog, Large.
FONTS = [('Arial', 12, False), ('Arial', 16, True), ('Times New Roman', 18, False),
         ('Times New Roman', 20, False), ('Times New Roman', 20, True)]


def entry(face, height, bold):
    font = ttf.TrueTypeFont(Path(gdi.FACES[(face.lower(), bold)]))
    metrics = font.metrics(height)
    widths = [metrics.widths.get(byte, 0) for byte in range(0x20, 0x100)]
    rows = [', '.join(f'{w:2d}' for w in widths[i:i + 16]) for i in range(0, len(widths), 16)]
    body = ',\n      '.join(rows)
    return (f'    {{ "{face}", {height}, {"true" if bold else "false"}, '
            f'{{ {metrics.ppem}, {metrics.ascent}, {metrics.descent} }},\n'
            f'      {{ {body} }} }},\n')


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[3] / 'src' / 'gdimetrics.inc'
    text = ('// Generated by tools/retail_runtime/slots/hud/gdi_metrics.py: GDI\'s metrics\n'
            '// for each FONT.DEF WINFONT -- { face, height, bold, { ppem, ascent,\n'
            '// descent }, the advance width of each Windows-1252 byte 0x20..0xff (0:\n'
            '// none) } -- from the Windows faces\' VDMX and hdmx tables. Do not edit.\n')
    text += ''.join(entry(*font) for font in FONTS)
    out.write_text(text)
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
