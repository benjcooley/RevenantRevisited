OBJECT "CAVDOOR1"
BEGIN
USE
 	BEGIN
	CONTROL OFF
	USER.STOP
	IF THIS.ISOUTSIDE user = 1
 		BEGIN
 			USER.GOTORELATIVEDISTANCE THIS 48 -32
 			USER.FACE 0
 			NOWAIT OPERATE user
 			NOWAIT USER.TRY "WOPENDOOROUT"
		END		
	ELSE
		BEGIN
 			USER.GOTORELATIVEDISTANCE THIS -52 32
 			USER.FACE 128
 			NOWAIT OPERATE user
 			NOWAIT USER.TRY "WOPENDOORIN"
		END
	WAIT 24
	FADESCREENOUT
	WAIT SCREENFADE
	nowait THIS.STATE "CLOSED"
	nowait THIS.STATE "CLOSED"
	ACTIVATE
	CONTROL ON
	FADESCREENIN
	END
END

